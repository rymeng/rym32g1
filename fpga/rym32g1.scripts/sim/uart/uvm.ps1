# =============================================================================
# uvm.ps1 - UART UVM 回归 / 覆盖率收集驱动
#
#   .\uvm.ps1                  编译 + 持续随机跑，按任意键停止并出覆盖率报告
#   .\uvm.ps1 -Iterations 20   跑固定轮数后自动停止并出覆盖率报告
#   .\uvm.ps1 -Tests crv -Seed 7
#   .\uvm.ps1 -RunTimeoutSec 300  单轮仿真墙钟超时（超时记 TIMEOUT，不算 FAIL）
#
# 依赖：Vivado xsim（xvlog / xelab / xsim / xcrg）。
#       优先用环境变量 XILINX_VIVADO，找不到再探测 C:\AMD\*\Vivado\bin\xvlog.bat。
#       所有生成物都在 <repo>\.dsh\uvm\ 下（该目录已在 .gitignore 中）。
# =============================================================================
[CmdletBinding()]
param(
    [int]    $Iterations = 0,          # 0 = 一直跑，按任意键停止
    [int]    $Seed       = 0,          # 0 = 每轮随机
    [string[]] $Tests    = @(),        # 空 = 全部；可选 crv/sweep/rx/tx/fix/buf/reg
    [string] $VivadoDir  = "",
    [switch] $NoCompile,
    [int]    $RunTimeoutSec = 300,
    [switch] $Quiet
)

$ErrorActionPreference = 'Stop'
# 仓库根：从脚本位置向上找包含 fpga\rym32g1.srcs\rtl\uart 的目录
$Root = $PSScriptRoot
for ($i = 0; $i -lt 6; $i++) {
    if (Test-Path (Join-Path $Root 'fpga\rym32g1.srcs\rtl\uart')) { break }
    $Root = Split-Path $Root -Parent
}
$RtlDir   = Join-Path $Root 'fpga\rym32g1.srcs\rtl\uart'
$SimDir   = Join-Path $Root '.pre\sim\uart_uvm'
$WorkDir  = Join-Path $Root '.dsh\uvm'
$CovDir   = Join-Path $WorkDir 'cov'
$LogDir   = Join-Path $WorkDir 'logs'
$RptDir   = Join-Path $WorkDir 'cov_report'

# ---------------------------------------------------------------- 工具定位 ---
function Find-Vivado {
    if ($VivadoDir -ne '' -and (Test-Path (Join-Path $VivadoDir 'bin\xvlog.bat'))) { return $VivadoDir }
    if ($env:XILINX_VIVADO) { if (Test-Path (Join-Path $env:XILINX_VIVADO 'bin\xvlog.bat')) { return $env:XILINX_VIVADO } }
    $cands = @()
    foreach ($base in @('C:\AMD', 'C:\Xilinx')) {
        if (Test-Path $base) {
            $cands += Get-ChildItem $base -Directory -ErrorAction SilentlyContinue |
                      ForEach-Object { Join-Path $_.FullName 'Vivado' } |
                      Where-Object { Test-Path (Join-Path $_ 'bin\xvlog.bat') }
        }
    }
    if ($cands.Count -gt 0) { return ($cands | Sort-Object -Descending | Select-Object -First 1) }
    throw 'xvlog.bat 未找到：请设置 XILINX_VIVADO 或用 -VivadoDir 指定 Vivado 安装目录'
}

$Vivado = Find-Vivado
$Bin    = Join-Path $Vivado 'bin'
$Xvlog  = Join-Path $Bin 'xvlog.bat'
$Xelab  = Join-Path $Bin 'xelab.bat'
$Xsim   = Join-Path $Bin 'xsim.bat'
$Xcrg   = Join-Path $Bin 'xcrg.bat'
$UvmSrc = Join-Path $Vivado 'data\system_verilog\uvm_1.2'
if (-not (Test-Path $UvmSrc)) { $UvmSrc = Join-Path $Vivado 'data\system_verilog\uvm_1.2' }

foreach ($d in @($WorkDir, $CovDir, $LogDir)) { New-Item -ItemType Directory -Force $d | Out-Null }

# --------------------------------------------------------------- 测试登记 ---
$AllTests = [ordered]@{
    'crv'   = @{ top = 'uart_tb_top_crv';   weight = 6 }   # 约束随机（RX + TX + 冲突）
    'sweep' = @{ top = 'uart_tb_top_sweep'; weight = 3 }   # 组合遍历
    'full'  = @{ top = 'uart_tb_top_full';  weight = 1 }   # 单库完整覆盖（sweep+conv+crv）
    'slow'  = @{ top = 'uart_tb_top_slow';  weight = 1 }   # 极端分频角落（SBR 256~2048）
    'rx'    = @{ top = 'uart_tb_top_rx';    weight = 1 }
    'tx'    = @{ top = 'uart_tb_top_tx';    weight = 1 }
    'fix'   = @{ top = 'uart_tb_top_fix';   weight = 1 }
    'buf'   = @{ top = 'uart_tb_top_buf';   weight = 1 }
    'reg'   = @{ top = 'uart_tb_top_reg';   weight = 1 }
}
if ($Tests.Count -eq 0) { $Tests = @($AllTests.Keys) }
foreach ($t in $Tests) {
    if (-not $AllTests.Contains($t)) { throw "未知测试 '$t'（可选：$($AllTests.Keys -join ', ')）" }
}

# ------------------------------------------------------------------ 编译 ---
function New-FileList {
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# generated by uvm.ps1')
    Get-ChildItem $SimDir -Directory -Recurse | ForEach-Object { $lines.Add("-i `"$($_.FullName)`"") }
    $lines.Add("-i `"$UvmSrc`"")
    Get-ChildItem $RtlDir -Filter *.sv | ForEach-Object { $lines.Add("`"$($_.FullName)`"") }
    $lines.Add("`"$(Join-Path $SimDir 'uart_if.sv')`"")
    $lines.Add("`"$(Join-Path $SimDir 'uart_pkg.sv')`"")
    $lines.Add("`"$(Join-Path $SimDir 'uart_tb_top.sv')`"")
    $path = Join-Path $WorkDir 'filelist.f'
    Set-Content -Path $path -Value $lines -Encoding ascii
    return $path
}

if (-not $NoCompile) {
    Write-Host "[uvm] Vivado : $Vivado"
    Write-Host "[uvm] 编译 UVM 包（NO_DPI 变体，避免缺少 DPI 链接库）"
    Push-Location $WorkDir
    try {
        & $Xvlog --sv --relax -d UVM_NO_DPI -d UVM_HDL_NO_DPI -d UVM_CMDLINE_NO_DPI -d UVM_REGEX_NO_DPI `
            -i "$UvmSrc" "$(Join-Path $UvmSrc 'xlnx_uvm_package.sv')" *> 'compile_uvm.log'
        if ($LASTEXITCODE -ne 0) { Get-Content 'compile_uvm.log' | Select-String 'ERROR' | Select-Object -First 10; throw 'UVM 包编译失败' }

        $fl = New-FileList
        Write-Host "[uvm] 编译 DUT + UVM 环境"
        & $Xvlog --sv --relax -f $fl *> 'compile_dut.log'
        if ($LASTEXITCODE -ne 0) { Get-Content 'compile_dut.log' | Select-String 'ERROR' | Select-Object -First 10; throw 'DUT/UVM 编译失败' }

        foreach ($t in $Tests) {
            $snap = "snap_$t"
            Write-Host "[uvm] 精化 $snap"
            & $Xelab --relax --cov_db_dir cov -s $snap $AllTests[$t].top *> "xelab_$t.log"
            if ($LASTEXITCODE -ne 0) { Get-Content "xelab_$t.log" | Select-String 'ERROR' | Select-Object -First 10; throw "精化 $snap 失败" }
        }
    } finally {
        Pop-Location
    }
}

# ------------------------------------------------------------ 运行 + 按键 ---
$script:StopRequested = $false
$script:CtrlC          = $false
try { [Console]::TreatControlCAsInput = $true } catch {}

function Test-StopKey {
    if ($script:StopRequested) { return $true }
    try {
        if ([Console]::KeyAvailable) {
            $null = [Console]::ReadKey($true)
            $script:StopRequested = $true
            return $true
        }
    } catch {
        try {
            if ($Host.UI.RawUI.KeyAvailable) { $null = $Host.UI.RawUI.ReadKey('NoEcho,IncludeKeyDown'); $script:StopRequested = $true; return $true }
        } catch { return $false }
    }
    return $false
}

function Invoke-Run {
    param([string]$Snap, [int]$SvSeed, [string]$CovName, [string]$LogPath)
    $cmdline = "/c `"`"$Xsim`" $Snap -R --sv_seed $SvSeed --cov_db_dir cov --cov_db_name $CovName > `"$LogPath`" 2>&1`""
    $p = Start-Process -FilePath 'cmd.exe' -ArgumentList $cmdline -PassThru -NoNewWindow -WorkingDirectory $WorkDir
    $killed = $false
    $timedOut = $false
    $sw = [Diagnostics.Stopwatch]::StartNew()
    while (-not $p.HasExited) {
        if (-not $killed -and -not $timedOut -and (Test-StopKey)) {
            $killed = $true
            & taskkill /T /F /PID $p.Id *> $null
            break
        }
        if (-not $timedOut -and ($RunTimeoutSec -gt 0) -and ($sw.Elapsed.TotalSeconds -gt $RunTimeoutSec)) {
            $timedOut = $true
            & taskkill /T /F /PID $p.Id *> $null
            break
        }
        Start-Sleep -Milliseconds 200
    }
    if (-not $killed) { $p.WaitForExit() }
    if ($timedOut) { return $false }
    return (-not $killed)
}

Write-Host ''
Write-Host '======================================================================'
Write-Host ' UART UVM 随机回归中…… 按任意键停止并生成覆盖率报告'
Write-Host " 覆盖率库 : $CovDir"
Write-Host '======================================================================'
Write-Host ''

$weights = @()
foreach ($t in $Tests) { for ($i = 0; $i -lt $AllTests[$t].weight; $i++) { $weights += $t } }
$run = 0
$pass = 0
$fail = 0
$rng = if ($Seed -ne 0) { [Random]::new($Seed) } else { [Random]::new() }
$started = Get-Date

while ($true) {
    if ($Iterations -gt 0 -and $run -ge $Iterations) { break }
    if (Test-StopKey) { break }

    $t    = $weights[$rng.Next(0, $weights.Count)]
    $snap = "snap_$t"
    $svSeed = if ($Seed -ne 0) { $Seed + $run } else { $rng.Next(1, 2147483000) }
    $covName = ("{0}_{1:D4}" -f $t, $run)
    $log = Join-Path $LogDir ("{0}.log" -f $covName)

    $run++
    $ok = Invoke-Run -Snap $snap -SvSeed $svSeed -CovName $covName -LogPath $log
    if ($ok -and (Test-Path $log)) {
        $txt = Get-Content $log -Raw
        $mErr = [regex]::Match($txt, 'UVM_ERROR\s*:\s*(\d+)')
        $mFat = [regex]::Match($txt, 'UVM_FATAL\s*:\s*(\d+)')
        $err = if ($mErr.Success) { [int]$mErr.Groups[1].Value } else { 0 }
        $fat = if ($mFat.Success) { [int]$mFat.Groups[1].Value } else { 0 }
        if ($err -eq 0 -and $fat -eq 0) { $pass++; $tag = 'PASS' } else { $fail++; $tag = "FAIL(UVM_ERROR=$err FATAL=$fat)" }
    } elseif (-not $ok) {
        $tag = 'TIMEOUT'
    } else {
        $fail++; $tag = 'FAIL(no log)'
    }
    if (-not $Quiet) {
        Write-Host ("[{0:HH:mm:ss}] #{1,-4} {2,-6} seed={3,-10} {4}" -f (Get-Date), $run, $t, $svSeed, $tag)
    }
    if ($script:StopRequested) { break }
}

# ------------------------------------------------------------ 覆盖率报告 ---
Write-Host ''
Write-Host "[uvm] 停止：共 $run 轮（PASS=$pass FAIL=$fail），用时 $([int]((Get-Date)-$started).TotalMinutes) 分钟"
$dbRoot = Join-Path $CovDir 'xsim.covdb'
if (Test-Path $dbRoot) {
    $dbs = Get-ChildItem $dbRoot -Directory | Select-Object -ExpandProperty Name
    Write-Host "[uvm] 覆盖率数据库 $($dbs.Count) 个，逐个生成 HTML 报告……"
    Remove-Item -Recurse -Force $RptDir -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force $RptDir | Out-Null
    Push-Location $WorkDir
    try {
        foreach ($db in $dbs) {
            & $Xcrg -cov_db_dir cov -cov_db_name $db -report_dir "cov_report\$db" -report_format html *> "xcrg_$db.log"
        }
    } finally {
        Pop-Location
    }
    Write-Host "[uvm] 报告目录：$RptDir（每个数据库一个子目录，打开 dashboard.html）"
    $fullLogs = Get-ChildItem $LogDir -Filter 'full_*.log' -ErrorAction SilentlyContinue | Sort-Object LastWriteTime
    if ($fullLogs.Count -gt 0) {
        Write-Host "[uvm] 以 full 测试（单库、已累积全部序列）为准的覆盖率："
        $covLines = Get-Content $fullLogs[-1].FullName -ErrorAction SilentlyContinue | Select-String '\[COV\]'
    } else {
        $covLines = Get-ChildItem $LogDir -Filter *.log -ErrorAction SilentlyContinue |
                    ForEach-Object { Get-Content $_.FullName -ErrorAction SilentlyContinue } |
                    Select-String '\[COV\]'
    }
    if ($covLines) {
        Write-Host '[uvm] 各 covergroup 覆盖率（取所有轮次中的最高值）：'
        $best = @{}
        foreach ($ln in $covLines) {
            if ($ln.Line -match '\[COV\]\s+(\w+)\s*=\s*([0-9.]+)%') {
                $g = $matches[1]; $v = [double]$matches[2]
                if (-not $best.ContainsKey($g) -or $best[$g] -lt $v) { $best[$g] = $v }
            }
        }
        foreach ($k in ($best.Keys | Sort-Object)) { Write-Host ("         {0,-10} {1,6:N2}%" -f $k, $best[$k]) }
    }
} else {
    Write-Host '[uvm] 没有覆盖率库（可能未运行任何一轮）'
}

if ($fail -gt 0) { exit 1 }
exit 0
